def shield(name, parts, th, deco):
    """parts: dict core/upper/lower -> (joint z, profile [(y,z)]). Plate faces -X; origin at bracket."""
    R.joint(name, None, (_n[0] * SPACING, 0, 0))
    _n[0] += 1
    xs = -0.36 - th / 2
    yo = 0.3
    for key in ('core', 'upper', 'lower'):
        jz, prof = parts[key]
        jn = '%s_%s' % (name, key)
        jp = (0, 0, 0) if key == 'core' else (xs, yo, jz)
        R.joint(jn, name, jp)
        p = R.pen(jn).at((-jp[0], -jp[1], -jp[2]))
        pr = [(y + yo, z) for y, z in prof]
        p.prism('A', pr, th, 'YZ', (xs, 0, 0), bv=0.06)
        cy = sum(y for y, z in pr) / len(pr)
        cz = sum(z for y, z in pr) / len(pr)
        p.prism('B', [(cy + (y - cy) * 0.72, cz + (z - cz) * 0.72) for y, z in pr], 0.12, 'YZ', (xs - th / 2 - 0.04, 0, 0), bv=0.03)
        for y, z in pr:
            p.bolt('F', (xs - th / 2, cy + (y - cy) * 0.86, cz + (z - cz) * 0.86), (-1, 0, 0), r=0.08)
        p.prism('F', [(cy + (y - cy) * 0.5, cz + (z - cz) * 0.6) for y, z in pr], 0.1, 'YZ', (xs + th / 2 + 0.03, 0, 0), bv=0.0)
        deco(key, p, xs - th / 2, cy, cz)
        if key == 'core':
            p.box('F', (0.4, 1.0, 1.3), (-0.2, 0, 0), bv=0.05)
            p.cyl('F', 0.34, 0.14, (-0.05, 0, 0), axis='X', n=10)
            for s in (-1, 1):
                p.rod('F', (-0.3, 0.3 * s, 0.5 * s), (xs, yo + 0.8 * s, 0.9 * s), 0.09, n=5)


