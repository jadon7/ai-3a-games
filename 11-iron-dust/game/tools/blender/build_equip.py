SPACING = 60.0
_n = [0]


def item(name):
    R.joint(name, None, (_n[0] * SPACING, 0, 0))
    _n[0] += 1
    return R.pen(name)


def muzzle(name, pos):
    R.joint(name + '_muzzle', name, pos)


def grip(p, z0=0.45):
    p.box('W', (0.4, 0.5, 1.05), (0, -0.06, -0.08), (rad(12), 0, 0), bv=0.05)
    p.box('F', (0.42, 0.3, 0.2), (0, -0.2, -0.6), (rad(12), 0, 0), bv=0.03)
    p.box('F', (0.26, 0.95, 0.07), (0, 0.5, -0.3), bv=0.0)
    p.box('F', (0.26, 0.07, 0.7), (0, 0.95, 0.05), bv=0.0)
    p.box('T', (0.1, 0.12, 0.35), (0, 0.42, 0.2), (rad(-15), 0, 0), bv=0.0)


def slots(p, x, y0, y1, z, n=4, h=0.14):
    for i in range(n):
        y = y0 + (y1 - y0) * (i + 0.5) / n
        for s in (-1, 1):
            p.line('T', (s * x, y - (y1 - y0) / n * 0.32, z), (s * x, y + (y1 - y0) / n * 0.32, z), (s, 0, 0), w=h)


