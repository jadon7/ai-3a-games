# 手画一张原创的三路两点俯视布局图（和给 AI 生图的配色规范一模一样），交给 tools/layout2map.py 转成地图数据。
# 坐标用米：x 向东，z 向南（图的上方是北 = 防守方）。比例 7 像素 / 米，图中心是原点。
# 用法：python3 tools/draw_layout.py 输出.png
import sys
import numpy as np
import cv2
S, C = 7.0, 512
img = np.full((1024, 1024, 3), 255, np.uint8)
COL = {'white': (255, 255, 255), 'ground': (0x4F, 0x6B, 0x78), 'high': (0x6E, 0x7F, 0x4A), 'low': (0x22, 0x31, 0x3F), 'stair': (0xF4, 0xC5, 0x42), 'cover': (0xB4, 0xB4, 0xB4),
       'siteA': (0xFF, 0x7A, 0x00), 'siteB': (0xE0, 0x39, 0x9B), 'spawnA': (0x35, 0xC7, 0x4A), 'spawnD': (0xE5, 0x39, 0x35)}
P = lambda pts: np.array([[C + x * S, C + z * S] for x, z in pts], np.int32)
def poly(kind, pts): cv2.fillPoly(img, [P(pts)], COL[kind][::-1])
def rect(kind, x0, z0, x1, z1): poly(kind, [(x0, z0), (x1, z0), (x1, z1), (x0, z1)])
def outline(kind, pts): cv2.polylines(img, [P(pts)], True, COL[kind][::-1], 4)

# ---------------- 地面（石板蓝）----------------
rect('ground', -38, 53, -14, 62)                                                    # 西口：出生区往西
poly('ground', [(-46, 26), (-36, 26), (-36, 53), (-38, 60), (-46, 60)])             # 西街
rect('ground', -53, 22, -40, 31)                                                    # 矿口房
poly('ground', [(-6, 50), (7, 50), (7, 32), (4, 28), (4, 13), (-6, 13), (-6, 28), (-5, 32)])   # 下街（中段错开一下）
rect('ground', 7, 34, 14, 41)                                                       # 下街边的小院（死角）
rect('ground', -2, 8, 4, 13)                                                        # 中门（窄口）
poly('ground', [(-14, 8), (11, 8), (15, 0), (13, -10), (-6, -13), (-15, -5)])       # 井台（中路枢纽）
rect('ground', -30, -10, -15, -4)                                                   # 西廊：井台 → A 东口
rect('ground', -36, -9, -26, 3)                                                     # 窗屋：西廊和矿道之间的小屋
poly('ground', [(-35, -24), (-28, -24), (-28, -10), (-35, -10)])                   # A 短道
rect('ground', -1, -54, 8, -8)                                                      # 中路北段：井台 → 防守方出生区
rect('ground', -38, -58, -1, -51)                                                   # A 后巷：防守方 → A
rect('ground', -38, -51, -31, -45)                                                  # A 北口
rect('ground', 8, -52, 36, -46)                                                     # B 后巷：防守方 → B
rect('ground', 16, 52, 35, 62)                                                      # 东口
poly('ground', [(34, 59), (46, 59), (52, 51), (52, -2), (40, -2), (40, 46), (34, 50)])   # 长街（长视线）
rect('ground', 52, 18, 58, 30)                                                      # 长街边的凹口
rect('ground', 30, -10, 52, -2)                                                     # 长街拐角
rect('ground', 36, -15, 44, -10)                                                    # B 长门（窄口）
rect('ground', -56, -27, -48, -15)                                                  # A 下口：矿道上来进 A
# 两个点位
A = [(-60, -48), (-40, -51), (-30, -45), (-28, -29), (-36, -24), (-56, -24), (-61, -31)]
B = [(30, -46), (52, -46), (58, -38), (58, -21), (47, -15), (32, -16), (29, -24), (29, -40)]
poly('ground', A); poly('ground', B)
# 出生区
poly('spawnA', [(-16, 67), (18, 67), (18, 56), (10, 50), (-8, 50), (-16, 56)])
poly('spawnD', [(-8, -67), (22, -67), (24, -58), (16, -52), (-4, -52), (-8, -58)])

# ---------------- 高台（橄榄绿）和下沉（深蓝）----------------
poly('low', [(-52, 18), (-44, 18), (-44, 4), (-47, -2), (-47, -10), (-54, -10), (-54, -2), (-52, 4)])   # 矿道（下沉）
rect('low', -47, -4, -36, 0)                                                        # 矿道侧口 → 窗屋
rect('high', -58, -48, -50, -40)                                                    # A 高台
rect('high', 11, -16, 24, -12); rect('high', 24, -26, 30, -12)                      # 东桥（高）：井台 → B 西台
rect('low', 46, -31, 54, -23)                                                       # B 坑（下沉）
rect('high', -14, 40, -6, 50)                                                       # 下街西侧的高台（俯视下街）

# ---------------- 楼梯（黄）----------------
rect('stair', -52, 18, -46, 22)                                                     # 矿口 → 矿道
rect('stair', -54, -15, -48, -10)                                                   # 矿道 → A 下口
rect('stair', -36, -4, -33, 0)                                                      # 矿道侧口 → 窗屋
rect('stair', -50, -46, -47, -42)                                                   # A 高台
rect('stair', 8, -16, 11, -11)                                                      # 井台 → 东桥
rect('stair', 30, -21, 33, -17)                                                     # B 西台 → B
rect('stair', 50, -23, 54, -20)                                                     # B 坑
rect('stair', -10, 44, -6, 48)                                                      # 下街高台（从下街上去）

# ---------------- 掩体（浅灰）----------------
for r in [(-4, 61, -1, 63), (8, 60, 11, 62), (-1, 38, 3, 42), (1, 20, 3, 23), (-10, 2, -7, 5), (5, -6, 8, -3), (-28, -8, -26, -6), (-44, 40, -42, 44),
          (-50, 26, -47, 28), (-50, 8, -48, 11), (-52, -34, -48, -31), (-38, -42, -35, -38), (-44, -30, -42, -28), (-57, -28, -55, -26), (36, 30, 39, 34), (49.5, 12, 52, 15),
          (42, 52, 45, 55), (36, -36, 40, -32), (44, -42, 47, -39), (52, -20, 55, -18), (38, -24, 40, -22), (14, -50, 17, -48), (-20, -56, -17, -53), (0, -40, 3, -37)]:
    rect('cover', *r)
# 出生区北口收窄成一道门（两边的白块是门楼），中路的长视线看不进出生区
rect('white', -9, 47.5, -2.5, 52); rect('white', 4, 47.5, 11, 52)
# 两个点位的线框
outline('siteA', A); outline('siteB', B)
cv2.imwrite(sys.argv[1], img)
# 各处的名字（像素坐标，转换时跟着地图一起换算）
import json
NAMES = [('西口', -26, 57), ('西街', -41, 42), ('矿口', -46, 26), ('矿道', -50, 6), ('窗屋', -31, -3), ('A 短道', -31.5, -17), ('A 下口', -52, -21), ('A 高台', -54, -44), ('A 北口', -34.5, -48),
         ('A 后巷', -20, -54.5), ('井台', 0, -1), ('中门', 1, 10.5), ('下街', 0, 30), ('下街高台', -10, 45), ('小院', 10.5, 37.5), ('西廊', -22, -7), ('中路北段', 3.5, -32), ('东桥', 18, -14),
         ('B 西台', 27, -20), ('东口', 26, 57), ('长街', 46, 24), ('长街拐角', 41, -6), ('B 长门', 40, -12.5), ('B 坑', 50, -27), ('B 后巷', 22, -49), ('凹口', 55, 24)]
json.dump([{'text': t, 'px': 512 + x * 7, 'py': 512 + z * 7} for t, x, z in NAMES], open(sys.argv[1].rsplit('.', 1)[0] + '.labels.json', 'w'), ensure_ascii=False)
print('ok')
